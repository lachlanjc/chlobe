import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { DOT_COUNT, DOT_TEXTURE_WIDTH } from './country-data-config.mjs';

const sourceDirectory = new URL('../src/', import.meta.url);
const outputPath = fileURLToPath(
  new URL('../src/generated-globe-shaders.ts', import.meta.url)
);
const dotTextureHeight = Math.ceil((DOT_COUNT + 1) / DOT_TEXTURE_WIDTH);

const minifyShader = (source) =>
  source
    .replaceAll('__DOT_TEXTURE_WIDTH__', `${DOT_TEXTURE_WIDTH}.0`)
    .replaceAll('__DOT_TEXTURE_HEIGHT__', `${dotTextureHeight}.0`)
    .replaceAll(/\/\/.*$/gmu, '')
    .replaceAll(/\s+/gu, ' ')
    .replaceAll(/\s*(?<token>[{}()[\],;=+*/<>-])\s*/gu, '$<token>')
    .trim();

const vertexSource = minifyShader(
  await readFile(new URL('globe.vert.glsl', sourceDirectory), 'utf-8')
);
const fragmentSource = minifyShader(
  await readFile(new URL('globe.frag.glsl', sourceDirectory), 'utf-8')
);
const quoteTypeScriptString = (source) =>
  `'${source.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

const generatedSource = `/**
 * Generated by scripts/generate-globe-shaders.mjs.
 * Do not edit by hand.
 */

export const GLOBE_VERTEX_SHADER =
  ${quoteTypeScriptString(vertexSource)};
export const GLOBE_FRAGMENT_SHADER =
  ${quoteTypeScriptString(fragmentSource)};
`;

await writeFile(outputPath, generatedSource);
